#!/usr/bin/env bash
set -u
export LC_ALL=C
unset CDPATH

here=$(CDPATH='' cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)
tmp=$(mktemp -d "${TMPDIR:-/tmp}/fingerprint-v63.XXXXXX") || exit 1
cleanup() { rm -rf "$tmp"; }
trap cleanup EXIT HUP INT TERM
pass=0
fail=0

ok() { pass=$((pass + 1)); printf 'ok %s - %s\n' "$pass" "$1"; }
bad() { fail=$((fail + 1)); printf 'not ok - %s\n' "$1"; }

# shellcheck source=../runtime.sh
. "$here/runtime.sh"

assert_changed() {
  ch_name=$1 ch_root=$2 ch_before=$fp
  ch_after=$(da_fingerprint "$ch_root")
  if [ "$ch_before" != "$ch_after" ]; then ok "$ch_name"; else bad "$ch_name"; fi
  fp=$ch_after
}

assert_unchanged() {
  uc_name=$1 uc_root=$2 uc_before=$fp
  uc_after=$(da_fingerprint "$uc_root")
  if [ "$uc_before" = "$uc_after" ]; then ok "$uc_name"; else bad "$uc_name"; fi
  fp=$uc_after
}

write_node() {
  wn_root=$1 wn_mode=$2
  mkdir -p "$wn_root/.agent/scripts" "$wn_root/.agent/memory" \
    "$wn_root/.agent/rules/learned" "$wn_root/.agent/indexes" "$wn_root/.agent/.state" "$wn_root/src"
  printf '%s\n' 'purpose' >"$wn_root/.agent/purpose.md"
  printf '%s\n' 'memory index' >"$wn_root/.agent/memory.md"
  printf '%s\n' 'memory fact' >"$wn_root/.agent/memory/fact.md"
  printf '%s\n' 'manual aggregate' >"$wn_root/.agent/rules/learned.md"
  printf '%s\n' 'manual learned record' >"$wn_root/.agent/rules/learned/record.md"
  printf '%s\n' '#!/usr/bin/env bash' 'exit 0' >"$wn_root/.agent/scripts/checks.sh"
  chmod +x "$wn_root/.agent/scripts/checks.sh"
  printf '%s\n' 'CHECK_DRIVER=.agent/scripts/checks.sh' >"$wn_root/.agent/scripts/verify.conf"
  printf '%s\n' 'log' >"$wn_root/.agent/session-log.md"
  printf '%s\n' 'state' >"$wn_root/.agent/.state/private"
  printf '%s\n' 'cache' >"$wn_root/.agent/indexes/cache"
  printf '%s\n' 'temporary log' >"$wn_root/.agent/verify-log.tmp"
  printf '%s\n' 'source' >"$wn_root/src/input"
  case "$wn_mode" in
    ignore-all) printf '%s\n' '.agent/' >"$wn_root/.gitignore" ;;
    track-shared)
      printf '%s\n' '.agent/*' '!.agent/purpose.md' '!.agent/rules/' '!.agent/docs/' >"$wn_root/.gitignore" ;;
  esac
  git -C "$wn_root" init -q
  git -C "$wn_root" config user.email test@example.invalid
  git -C "$wn_root" config user.name Test
  git -C "$wn_root" add .
  git -C "$wn_root" commit -qm initial
}

for mode in ignore-all track-shared; do
  root="$tmp/$mode"
  write_node "$root" "$mode"
  fp=$(da_fingerprint "$root")

  printf '%s\n' '# driver change' >>"$root/.agent/scripts/checks.sh"
  assert_changed "$mode: ignored driver changes fingerprint" "$root"
  printf '%s\n' 'TIMEOUT_SECONDS=9' >>"$root/.agent/scripts/verify.conf"
  assert_changed "$mode: ignored config changes fingerprint" "$root"
  printf '%s\n' 'memory change' >>"$root/.agent/memory/fact.md"
  assert_changed "$mode: memory record changes fingerprint" "$root"
  printf '%s\n' 'learned change' >>"$root/.agent/rules/learned/record.md"
  assert_changed "$mode: manual learned record changes fingerprint" "$root"
  printf '%s\n' 'aggregate change' >>"$root/.agent/rules/learned.md"
  assert_changed "$mode: manual learned aggregate changes fingerprint" "$root"

  mkdir -p "$root/.verify"
  printf '%s\n' '.verify/' >>"$root/.gitignore"
  printf '%s\n' 'project driver' >"$root/.verify/checks.sh"
  export DA_CHECK_DRIVER=.verify/checks.sh
  fp=$(da_fingerprint "$root")
  printf '%s\n' 'project driver change' >>"$root/.verify/checks.sh"
  assert_changed "$mode: ignored project-owned driver changes fingerprint" "$root"
  unset DA_CHECK_DRIVER
  fp=$(da_fingerprint "$root")

  printf '%s\n' 'log change' >>"$root/.agent/session-log.md"
  assert_unchanged "$mode: session log stays excluded" "$root"
  printf '%s\n' 'state change' >>"$root/.agent/.state/private"
  assert_unchanged "$mode: state stays excluded" "$root"
  printf '%s\n' 'cache change' >>"$root/.agent/indexes/cache"
  assert_unchanged "$mode: generated cache stays excluded" "$root"
  printf '%s\n' 'temporary change' >>"$root/.agent/verify-log.tmp"
  assert_unchanged "$mode: managed log temporary stays excluded" "$root"

  printf '%s\n' '<!-- Generated by index.sh from rules/learned/ records. -->' 'generated one' \
    >"$root/.agent/rules/learned.md"
  fp=$(da_fingerprint "$root")
  printf '%s\n' '<!-- Generated by index.sh from rules/learned/ records. -->' 'generated two' \
    >"$root/.agent/rules/learned.md"
  assert_unchanged "$mode: genuine generated learned aggregate stays excluded" "$root"

  git -C "$root" add -f .agent/session-log.md .agent/.state/private \
    .agent/indexes/cache .agent/verify-log.tmp .agent/rules/learned.md
  assert_unchanged "$mode: staging excluded paths stays excluded" "$root"
  printf '%s\n' 'staged log change' >>"$root/.agent/session-log.md"
  printf '%s\n' 'staged state change' >>"$root/.agent/.state/private"
  git -C "$root" add -f .agent/session-log.md .agent/.state/private
  assert_unchanged "$mode: staged exclusion edits stay excluded" "$root"

  mkdir -p "$tmp/external-$mode"
  printf '%s\n' 'external one' >"$tmp/external-$mode/input"
  ln -s "$tmp/external-$mode" "$root/.agent/external"
  fp=$(da_fingerprint "$root")
  printf '%s\n' 'external two' >"$tmp/external-$mode/input"
  assert_unchanged "$mode: external symlink contents are never followed" "$root"
done

sub_source="$tmp/submodule-source"
mkdir "$sub_source"
git -C "$sub_source" init -q
git -C "$sub_source" config user.email test@example.invalid
git -C "$sub_source" config user.name Test
printf '%s\n' 'submodule one' >"$sub_source/tracked.txt"
git -C "$sub_source" add tracked.txt
git -C "$sub_source" commit -qm one
sub_first=$(git -C "$sub_source" rev-parse HEAD)
printf '%s\n' 'submodule two' >"$sub_source/tracked.txt"
git -C "$sub_source" commit -qam two
sub_second=$(git -C "$sub_source" rev-parse HEAD)

sub_parent="$tmp/submodule-parent"
mkdir "$sub_parent"
git -C "$sub_parent" init -q
git -C "$sub_parent" config user.email test@example.invalid
git -C "$sub_parent" config user.name Test
git -C "$sub_parent" -c protocol.file.allow=always submodule add -q "$sub_source" modules/child
git -C "$sub_parent" commit -qm 'add submodule'
fp=$(da_fingerprint "$sub_parent")
git -C "$sub_parent/modules/child" checkout -q "$sub_first"
assert_changed 'checked-out submodule commit changes fingerprint' "$sub_parent"
git -C "$sub_parent/modules/child" checkout -q "$sub_second"
fp=$(da_fingerprint "$sub_parent")
printf '%s\n' 'tracked working edit' >>"$sub_parent/modules/child/tracked.txt"
assert_changed 'tracked submodule working edit changes fingerprint' "$sub_parent"
git -C "$sub_parent/modules/child" checkout -q -- tracked.txt

uninitialized="$tmp/submodule-uninitialized"
git -c protocol.file.allow=always clone -q --no-recurse-submodules "$sub_parent" "$uninitialized"
if da_fingerprint "$uninitialized" >"$tmp/uninitialized.fp" 2>"$tmp/uninitialized.err"; then
  ok 'uninitialized submodule is fingerprinted without parent recursion'
else
  bad 'uninitialized submodule fingerprint failed'
fi
printf '%s\n' 'unexpected contents' >"$uninitialized/modules/child/input"
da_fingerprint "$uninitialized" >"$tmp/uninitialized-nonempty.fp" 2>"$tmp/uninitialized-nonempty.err"
uninitialized_rc=$?
if [ "$uninitialized_rc" -eq 2 ] && grep -q 'unsupported nonempty uninitialized submodule' "$tmp/uninitialized-nonempty.err"; then
  ok 'nonempty uninitialized submodule fails at an explicit boundary'
else
  bad 'nonempty uninitialized submodule was accepted opaquely'
fi

external_sub="$tmp/external-submodule-target"
mkdir "$external_sub"
printf '%s\n' 'external one' >"$external_sub/input"
rm -rf "$sub_parent/modules/child"
ln -s "$external_sub" "$sub_parent/modules/child"
fp=$(da_fingerprint "$sub_parent")
printf '%s\n' 'external two' >"$external_sub/input"
assert_unchanged 'gitlink symlink never follows external contents' "$sub_parent"

non_git="$tmp/non-git"
mkdir -p "$non_git/.agent/scripts" "$non_git/app"
printf '%s\n' 'canonical' >"$non_git/.agent/memory.md"
printf '%s\n' 'driver' >"$non_git/.agent/scripts/checks.sh"
printf '%s\n' 'config' >"$non_git/.agent/scripts/verify.conf"
printf '%s\n' 'explicit' >"$non_git/app/input"
export DA_NON_GIT_INPUT_ROOTS='app'
non_fp=$(da_fingerprint "$non_git")
fp=$non_fp
printf '%s\n' 'canonical change' >>"$non_git/.agent/memory.md"
assert_changed 'non-Git canonical node source stays covered' "$non_git"
printf '%s\n' 'explicit change' >>"$non_git/app/input"
assert_changed 'non-Git explicit source input stays covered' "$non_git"
unset DA_NON_GIT_INPUT_ROOTS

printf 'fingerprint-v63: %s passed, %s failed\n' "$pass" "$fail"
[ "$fail" -eq 0 ]
